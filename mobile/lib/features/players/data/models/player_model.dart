import '../../domain/entities/player.dart';

/// Player data model extending domain [Player] entity with API serialization.
class PlayerModel extends Player {
  const PlayerModel({
    required super.id,
    required super.user,
    required super.name,
    super.avatar,
    super.playingRole = 'BATSMAN',
    super.battingStyle = 'RIGHT_HAND',
    super.bowlingStyle = 'NONE',
    super.jerseyNumber,
    super.dateOfBirth,
    super.city,
    super.bio,
    super.matchesCount = 0,
    super.runs = 0,
    super.ballsFaced = 0,
    super.wickets = 0,
    super.oversBowled = 0,
    super.runsConceded = 0,
    super.battingAverage = 0.0,
    super.strikeRate = 0.0,
    super.bowlingAverage = 0.0,
    super.economyRate = 0.0,
    super.highestScore = 0,
    super.bestBowling,
    super.catches = 0,
    super.stumpings = 0,
  });

  factory PlayerModel.fromJson(Map<String, dynamic> json) {
    final map = json.containsKey('player') && json['player'] is Map<String, dynamic>
        ? json['player'] as Map<String, dynamic>
        : json;

    final base = Player.fromJson(map);

    return PlayerModel(
      id: base.id,
      user: base.user,
      name: base.name,
      avatar: base.avatar,
      playingRole: base.playingRole,
      battingStyle: base.battingStyle,
      bowlingStyle: base.bowlingStyle,
      jerseyNumber: base.jerseyNumber,
      dateOfBirth: base.dateOfBirth,
      city: base.city,
      bio: base.bio,
      matchesCount: base.matchesCount,
      runs: base.runs,
      ballsFaced: base.ballsFaced,
      wickets: base.wickets,
      oversBowled: base.oversBowled,
      runsConceded: base.runsConceded,
      battingAverage: base.battingAverage,
      strikeRate: base.strikeRate,
      bowlingAverage: base.bowlingAverage,
      economyRate: base.economyRate,
      highestScore: base.highestScore,
      bestBowling: base.bestBowling,
      catches: base.catches,
      stumpings: base.stumpings,
    );
  }

  factory PlayerModel.fromEntity(Player entity) {
    return PlayerModel(
      id: entity.id,
      user: entity.user,
      name: entity.name,
      avatar: entity.avatar,
      playingRole: entity.playingRole,
      battingStyle: entity.battingStyle,
      bowlingStyle: entity.bowlingStyle,
      jerseyNumber: entity.jerseyNumber,
      dateOfBirth: entity.dateOfBirth,
      city: entity.city,
      bio: entity.bio,
      matchesCount: entity.matchesCount,
      runs: entity.runs,
      ballsFaced: entity.ballsFaced,
      wickets: entity.wickets,
      oversBowled: entity.oversBowled,
      runsConceded: entity.runsConceded,
      battingAverage: entity.battingAverage,
      strikeRate: entity.strikeRate,
      bowlingAverage: entity.bowlingAverage,
      economyRate: entity.economyRate,
      highestScore: entity.highestScore,
      bestBowling: entity.bestBowling,
      catches: entity.catches,
      stumpings: entity.stumpings,
    );
  }

  Player toEntity() {
    return Player(
      id: id,
      user: user,
      name: name,
      avatar: avatar,
      playingRole: playingRole,
      battingStyle: battingStyle,
      bowlingStyle: bowlingStyle,
      jerseyNumber: jerseyNumber,
      dateOfBirth: dateOfBirth,
      city: city,
      bio: bio,
      matchesCount: matchesCount,
      runs: runs,
      ballsFaced: ballsFaced,
      wickets: wickets,
      oversBowled: oversBowled,
      runsConceded: runsConceded,
      battingAverage: battingAverage,
      strikeRate: strikeRate,
      bowlingAverage: bowlingAverage,
      economyRate: economyRate,
      highestScore: highestScore,
      bestBowling: bestBowling,
      catches: catches,
      stumpings: stumpings,
    );
  }

  @override
  PlayerModel copyWith({
    String? id,
    String? user,
    String? name,
    String? avatar,
    String? playingRole,
    String? battingStyle,
    String? bowlingStyle,
    int? jerseyNumber,
    DateTime? dateOfBirth,
    String? city,
    String? bio,
    int? matchesCount,
    int? runs,
    int? ballsFaced,
    int? wickets,
    int? oversBowled,
    int? runsConceded,
    double? battingAverage,
    double? strikeRate,
    double? bowlingAverage,
    double? economyRate,
    int? highestScore,
    String? bestBowling,
    int? catches,
    int? stumpings,
  }) {
    return PlayerModel(
      id: id ?? this.id,
      user: user ?? this.user,
      name: name ?? this.name,
      avatar: avatar ?? this.avatar,
      playingRole: playingRole ?? this.playingRole,
      battingStyle: battingStyle ?? this.battingStyle,
      bowlingStyle: bowlingStyle ?? this.bowlingStyle,
      jerseyNumber: jerseyNumber ?? this.jerseyNumber,
      dateOfBirth: dateOfBirth ?? this.dateOfBirth,
      city: city ?? this.city,
      bio: bio ?? this.bio,
      matchesCount: matchesCount ?? this.matchesCount,
      runs: runs ?? this.runs,
      ballsFaced: ballsFaced ?? this.ballsFaced,
      wickets: wickets ?? this.wickets,
      oversBowled: oversBowled ?? this.oversBowled,
      runsConceded: runsConceded ?? this.runsConceded,
      battingAverage: battingAverage ?? this.battingAverage,
      strikeRate: strikeRate ?? this.strikeRate,
      bowlingAverage: bowlingAverage ?? this.bowlingAverage,
      economyRate: economyRate ?? this.economyRate,
      highestScore: highestScore ?? this.highestScore,
      bestBowling: bestBowling ?? this.bestBowling,
      catches: catches ?? this.catches,
      stumpings: stumpings ?? this.stumpings,
    );
  }
}
